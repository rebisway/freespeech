# Turns the mobile app's icons (sources/freespeech.mobile/Resources/Images/ic_*.svg, Material icons: one 24x24 path each) into drawing
# geometries for the desktop client: sources/freespeech.desktop/Styles/Icons.axaml, one StreamGeometry per icon, named like the file
# (ic_chat.svg -> Icon.chat). The desktop paints them with the text colour, so one icon fits every theme.
#
# USAGE:  scripts\gen-desktop-icons.ps1      (run again when an icon of the mobile app changes)

$root = Split-Path -Parent $PSScriptRoot
$images = Join-Path $root 'sources\freespeech.mobile\Resources\Images'
$out = Join-Path $root 'sources\freespeech.desktop\Styles\Icons.axaml'

$lines = foreach ($file in Get-ChildItem $images -Filter 'ic_*.svg' | Sort-Object Name) {
    $svg = [IO.File]::ReadAllText($file.FullName)
    $paths = [regex]::Matches($svg, '<path[^>]*\sd="([^"]+)"') | ForEach-Object { $_.Groups[1].Value }
    if (-not $paths) { continue }
    $name = 'Icon.' + $file.BaseName.Substring(3)
    "`t<StreamGeometry x:Key=`"$name`">$($paths -join ' ')</StreamGeometry>"
}

$xml = @"
<!--
  FreeSpeech - P2P Encrypted Messaging
  Copyright (c) 2024-2026 Thomas Gourgnier
  Licensed under the GNU Affero General Public License v3.0 or later.
  SPDX-License-Identifier: AGPL-3.0-or-later

  Generated by scripts/gen-desktop-icons.ps1 from the mobile app's icons: do not edit by hand.
-->
<ResourceDictionary xmlns="https://github.com/avaloniaui" xmlns:x="http://schemas.microsoft.com/winfx/2006/xaml">
$($lines -join "`r`n")
</ResourceDictionary>
"@
[IO.File]::WriteAllText($out, $xml, (New-Object Text.UTF8Encoding($true)))
"$($lines.Count) icons written to $out"
